#!/bin/bash
# One-time setup on the Mac:  ./setup_mac.sh
#  1. Creates LearnWise/Config/Secrets.xcconfig from .env (or asks for the Gemini key)
#  2. Regenerates LearnWise.xcodeproj if XcodeGen is installed (optional; it's already committed)
#  3. Opens the project in Xcode
set -euo pipefail
cd "$(dirname "$0")"

SECRETS=LearnWise/Config/Secrets.xcconfig

read_env() {   # read_env NAME -> value from .env (empty if missing)
  [ -f .env ] || return 0
  grep -E "^[[:space:]]*$1[[:space:]]*=" .env | tail -1 | sed -E "s/^[^=]*=[[:space:]]*//; s/[[:space:]]*$//; s/^[\"']//; s/[\"']$//"
}

if [ -f "$SECRETS" ]; then
  echo "✓ $SECRETS already exists (left unchanged)"
else
  KEY="$(read_env GEMINI_API_KEY)"
  MODEL="$(read_env GEMINI_MODEL)"
  YT="$(read_env YOUTUBE_API_KEY)"
  if [ -z "$KEY" ]; then
    echo "No GEMINI_API_KEY found in .env."
    read -r -p "Paste your Gemini API key (or press Enter to run offline-only): " KEY
  fi
  cat > "$SECRETS" <<EOF
// Generated by setup_mac.sh (gitignored). Never commit this file.
GEMINI_API_KEY = ${KEY}
GEMINI_MODEL = ${MODEL:-gemini-3.8-flash}
YOUTUBE_API_KEY = ${YT}
EOF
  if [ -n "$KEY" ]; then echo "✓ Wrote $SECRETS with your Gemini key"; else echo "✓ Wrote $SECRETS without a key (offline catalog only)"; fi
fi

if command -v xcodegen >/dev/null 2>&1; then
  xcodegen generate --spec project.yml --quiet && echo "✓ Regenerated LearnWise.xcodeproj"
else
  echo "• XcodeGen not installed. Using the committed LearnWise.xcodeproj (that's fine)"
fi

open LearnWise.xcodeproj
echo "✓ Opened Xcode. Pick an iPhone simulator and press ⌘R (⌘U runs the tests)."
